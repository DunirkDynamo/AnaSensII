def find_peak_spsignal(I):
    """
    Using scipy.signal.find_peaks function, this locates the peak position.
    Now pretty much obselete...

    Parameters :
        I : numpy n x 1 array
            smoothed approxiamtion of measured current.
    Returns :
        max1 : int
            indice of the start of the peak
        min1 : int
            indice of the maximum of the peak
        max2 : int
            indice of the end of the peak
    """
    min1,prop = signal.find_peaks(-I,
                                    height=None,
                                    threshold=None,
                                    prominence =None,
                                    width = [len(I)/20,len(I)/1.3])
    if min1.size == 0:
        return 0,0,0

    else:
        l = np.argmax(prop['prominences'])
        max1, max2, min1 = prop['left_bases'][l],prop['right_bases'][l],min1[l]

        d1 = min1 - max1
        d2 = max2 - min1

        if d1/d2 > 2:
            max1 = int(min1 - 2*d2/(prop['right_ips'][l] - min1)*(min1 - prop['left_ips'][l]))
        elif d1/d2 < 0.5:
            max2 = int(min1 + 2*d1/(min1 - prop['left_ips'][l])*(prop['right_ips'][l] - min1))

        return max1, max2, min1

def naive_derivate(x,y):
    """
    Evaluate the derivative of some curve.  This is  pretty much the simplest way
    one could do this... Not very pertinent...

    Parameters :
        x :numpy n dim array ; 
            The x data
        y : numpy n dim array ;
            the y data
    Returns:
        d: numpy n-1 dim array ;
            the derivative of the curve
        xd: numpy n-1 dim array ;
            the associated x value of d
    """
    d = (y[1:] - y[:-1])/(x[1:] - x[:-1])
    xd = (x[1:] + x[:-1])/2
    return xd,d

