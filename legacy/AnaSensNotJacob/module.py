def read_mpt(filepath):
    """
    Permet à l'utilisateur d'extraire les informations contenues dans les fichiers
    mpt produits dans le laboratoire de Phillippe.  Cette version ne fonctionne 
    si toutes les expériences contiennent exactement le même nombre de points
    de mesures. Renvoie deux tableaux numpy, l'un contenant les potentiels (Vs)
    et l'autre les courrants associés (Is).

    Parameters:
        data_path: str or Path object;
            The path pointing to the location of the mpt file.
    Returns:
        Vs: np.array;
            contains the potential mesures.
        Is : np.array;
            contains the associated current.
    """
    with open(filepath) as f:
        data = [i.rstrip('\n ') for i in f.readlines()]

    n_header_line = int(data[1].split(' ')[-1])

    header = data[:n_header_line]
    values = [s.replace(',','.') for s in data[n_header_line:]]

