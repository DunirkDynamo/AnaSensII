def data_smoothing_vect(V,I,savgol_win_len = 9, savgol_polyorder = 1, polyfit_order = 60):
    """
    A vectorised version of the data_smoothing function. Make uses of the 
    already implemented vectorisation capabilities of numpy.

    Parameters:
        V: m x n np.array;
            The potential values as a m x n array (m curves containing each n
            data points)
        I: m x n np.array;
            The current values as a m x n array (m curves containing each n
            data points)
        win_len : (optional, default = 9), odd int:
            Length of the window that is used in the iterating smoothing process
            of the Savintsky-Golay filter. MUST BE AN ODD INTEGER
        polyorder : (optional, default = 1), int:
            Order of the polynome fit done inside of each of the Savitsky-Golay
            smoothing window. Shouldn't be higher than 3...
        polyfit_order : (optional, default = 60), int;
            Order of the final polynome fit done on the result of the Savitsky-
            Golay filter. Should be pretty high to allow the fit to approximate
            our data well.
        coeffs : (optional, default = False) Boolean;
            If true, will return not only the smoothed data, but the coefficients
            of the last polynome fit as well.
    Returns:
        smooth : m x n np.array;
            A smoothed version of the I data
        polynomial_coeffs :(opt) (polyfit_order + 1) x n np.array:
            The coefficients of the polynome fit of the data (usefull if you
            want to derivate or integrate the curve).

    """
    savgol_filtered = signal.savgol_filter(I,
                              window_length = savgol_win_len,
                              polyorder = savgol_polyorder
                            )
    polynomial_coeffs = np.polyfit(V[0,:],savgol_filtered.T,deg = polyfit_order)
    smooth = np.polyval(polynomial_coeffs,V.T).T

    return smooth,polynomial_coeffs

def polyder_vect(V,coeffs):
    """
    An homemade version of a vectorised equivalent of np.polyder function.

    Parameters:
        V: m x n np.array;
            The potential values as a m x n array (m curves containing each n
            data points)
        coeffs: (polyfit_order + 1) x n np.array:
            The coefficients of the polynome fit of the data.
    Returns:
        d: m x n np.array;
            The derivative of the curve (dI/dV) evaluated at V
    """
    d_coeffs = (coeffs.T * np.arange(coeffs.shape[0])[-1::-1]).T[:-1,:]
    d = np.polyval(d_coeffs,V.T).T
    return d

def polyprimitivecoeffs_vect(coeffs):
    """
    A homemade version of a vectorized version of np.polyint.
    Parameters:
        coeffs: (polyfit_order + 1) x n np.array:
            The coefficients of the polynome fit of the data.
    Returns:
        prim_coeffs: (coeffs.shape[0]+1) x n np.array;
            The coefficient of the primitive of the polynome which fits our 
            data. Usefull for an easy and efficient integration
    """
    primitive_coeffs = (coeffs.T/(np.arange(0,coeffs.shape[0]) + 1)[-1::-1]).T
    return np.append(primitive_coeffs,np.zeros((1,coeffs.shape[-1])),axis = 0)

