def droite(x,m,b):
    """
    Given x values, returns the the y values of a line with slope m and 
    intercept b.

    Parameters:
        x: numpy n dim array ;
            The x values
        m: float ;
            The slope
        b: float ;
            The intercept
    Returns:
        y : numpy n dim array:
            y = m*x + b

    """
    return m*x+b

def droite_param(x1,x2,y1,y2):
    """
    Given two points, finds the parameters of the line passing by those points

    Parameters:
        x1 : float;
            The x value of the first point
        x2 : float ;
            The x value of the second point
        y1 : float ;
            The y value of the first point
        y2 : float ;
            The y value of the second point
    Returns:
        m : float;
            The slope of the line
        b : float;
            The intercept of the line
    """
    m = (y2-y1)/(x2 - x1)
    b = y2- m*x2
    return m,b

