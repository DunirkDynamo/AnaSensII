def data_smoothing(V,I,win_len = 9, polyorder = 1, polyfit_order = 60,coeffs = False):
    """
    This function approximate experimental data as a continuous function. First,
    a Savintsky-Golay filter is used, followed by polynome fit on the result giving
    as a result a good « smooth » approximation of our noised data.
    We should be carefull as sometimes the polyfit converges badly on some of 
    data. For example, the polynome fit is not very good on the CV measurements.

    Parameters:
        V : numpy n dim array
            The different potential values of the experiment
        I : numpy n dim array
            The associated measured current.
        win_len : (optional, default = 9), odd int:
            Length of the window that is used in the iterating smoothing process
            of the Savintsky-Golay filter. MUST BE AN ODD INTEGER
        polyorder : (optional, default = 1), int:
            Order of the polynome fit done inside of each of the Savitsky-Golay
            smoothing window. Shouldn't be higher than 3...
        polyfit_order : (optional, default = 60), int;
            Order of the final polynome fit done on the result of the Savitsky-
            Golay filter. Should be pretty high to allow the fit to approximate
            our data well.
        coeffs : (optional, default = False) Boolean;
            If true, will return not only the smoothed data, but the coefficients
            of the last polynome fit as well.
    Returns:
        smooth : numpy n dim array;
            A smoothed version of the I data
        polynomail_coeffs :(opt) numpy polyfit_order + 1 dimension:
            The coefficients of the last polynome fit of the data.
    """
    smooth_currents = signal.savgol_filter(I,window_length = win_len,polyorder = polyorder)
    polynomial_coeffs = np.polyfit(V,smooth_currents,deg = polyfit_order)
    eval_regression = np.polyval(polynomial_coeffs,V)

    if coeffs:
        return eval_regression,polynomial_coeffs
    else:
        return eval_regression

def findpeaksp(V,I,d):
    """
    Given the V,I and dI/dV data, evaluates the current pic position on the curve

    Parameters:
        V: np.array;
            The potential values of the curve.
        I: np.array;
            The associated current values.
        d: np.array;
            dI/dV evaluated at V.  The derivative of the curve.

    Returns:
        max1: int;
            indice of the position of the start of the current peak.
        max2: int;
            indice of the position of the end of the current peak.
        min1: int;
            indice of the position of the center of the current peak.
    """
    # We first use scipy.signal.find_peaks to have a first approximation of the
    # peak location
    min1,prop = signal.find_peaks(abs(I),
                                    height=None,
                                    threshold=None,
                                    prominence =None,
                                    width = [len(I)/20,len(I)/1.3])
    # If no peaks are found, the function returns 0 everywhere
    if min1.size == 0:
        return 0,0,0
    # We only keep the peak which have the highest prominence
    l = np.argmax(prop['prominences'])
    # The start and end of the peak are interpreted as being the left_base and
    # right_base as given by the scipy.signals.find_peaks function. 
    max1, max2, min1 = prop['left_bases'][l],prop['right_bases'][l],min1[l]
    results = signal.peak_widths(abs(I), [min1])
    width = results[0][0]
    width_height = results[1][0]
    # Distance between start and middle and between middle and end of the Peak
    d1 = min1 - max1
    d2 = max2 - min1

    # if the peak is too asymetrical, we adjust it a little bit (maybe this is
    # not a good thing to do and could lead to avoidable errors... We should keep
    # an eye on this)
    """
    if d1/d2 > 2:
        max1 = int(min1 - 2*d2/(prop['right_ips'][l] - min1)*(min1 - prop['left_ips'][l]))
    elif d1/d2 < 0.5:
        max2 = int(min1 + 2*d1/(min1 - prop['left_ips'][l])*(prop['right_ips'][l] - min1))
    """
    # Now we refine the peak start and end position. The side that has the 
    # highest current is adjusted first.
    if I[max1] > I[max2]:
        #adjust left (right on the graphics)
        #the data from the left_ips to the end
        v_ = V[:int(prop['left_ips'][l])]
        c_ = I[:int(prop['left_ips'][l])]
        d_ = d[:int(prop['left_ips'][l])]
        # the slope the line between max1 and max2 would have for each possible max1 in c_
        m_ = (I[max2] - c_)/(V[max2] - v_)
        score = abs(m_ - d_) #how much is the line tangeant to the data curve 
        #score = abs(1 - m_/d_) # *****

        #we isolate local minima in "possible"
        first = np.where(score[:-1] < score[1:])[0]
        second = np.where(score[1:] < score[:-1])[0] + 1
        possible = np.intersect1d(first,second)
        #we only keep the local minimas which are tangeant <<enough>> to the data
        #possible = np.array([i for i in possible if score[i] <= 1]) # ****


        if possible.size == 0: 
            return 0,0,0
        # we take the posssible value nearest to the peak     
        new_max1 = max(possible)

        #adjust right
        #the data from the right_ips to the end
        v_ = V[int(prop['right_ips'][l]):]
        c_ = I[int(prop['right_ips'][l]):]
        d_ = d[int(prop['right_ips'][l]):]
        # the slope the line between new_max1 and max2 would have for each possible max2 in c_
        m_ = (c_ - I[new_max1])/(v_ - V[new_max1])
        score = abs(m_ - d_) #how much is the line tangeant to the data curve
        #score = abs(1 - m_/d_) #*****

        #we isolate local minima in "possible"
        first = np.where(score[:-1] < score[1:])[0]
        second = np.where(score[1:] < score[:-1])[0] + 1
        possible = np.intersect1d(first,second)
        #we only keep the local minimas which are tangeant <<enough>> to the data
        #possible = np.array([i for i in possible if score[i] <= 1]) # ****

        if possible.size == 0: 
            return 0,0,0        
        # We keep the one nearest to the peak
        new_max2 = min(possible) + int(prop['right_ips'][l])

    else :
        #adjust right
        #the data from the right_ips to the end
        v_ = V[int(prop['right_ips'][l]):]
        c_ = I[int(prop['right_ips'][l]):]
        d_ = d[int(prop['right_ips'][l]):]
        # the slope the line between max1 and max2 would have for each possible max2 in c_
        m_ = (c_ - I[max1])/(v_ - V[max1])
        score = abs(m_ - d_) #how much is the line tangeant to the data curve 
        #score = abs(1 - m_/d_) # *****

        #we isolate local minima in "possible"
        first = np.where(score[:-1] < score[1:])[0]
        second = np.where(score[1:] < score[:-1])[0] + 1
        possible = np.intersect1d(first,second)
        #we only keep the local minimas which are tangeant <<enough>> to the data
        #possible = np.array([i for i in possible if score[i] <= 1]) # ****


        if possible.size == 0: 
            return 0,0,0
        # We keep the one nearest to the peak
        new_max2 = min(possible) + int(prop['right_ips'][l])

        #adjust left
        #the data from the left_ips to the end
        v_ = V[:int(prop['left_ips'][l])]
        c_ = I[:int(prop['left_ips'][l])]
        d_ = d[:int(prop['left_ips'][l])]
        # the slope the line between max1 and max2 would have for each possible max2 in c_
        m_ = (I[new_max2] - c_)/(V[new_max2] - v_)
        score = abs(m_ - d_) #how much is the line tangeant to the data curve 
        #score = abs(1 - m_/d_) # *****

        #we isolate local minima in "possible"
        first = np.where(score[:-1] < score[1:])[0]
        second = np.where(score[1:] < score[:-1])[0] + 1
        possible = np.intersect1d(first,second)
        #we only keep the local minimas which are tangeant <<enough>> to the data
        #possible = np.array([i for i in possible if score[i] <= 1]) # ****

        # if there is no possibility at this point, the function returns 0,0,0
        if possible.size == 0: 
            return 0,0,0
        new_max1 = max(possible)

    return new_max1, new_max2, min1, width, width_height

def get_peakheight(V,smoothed_current,max1,max2,ipeak):
    """
    Evaluates a line between the start and the end of a peak and measures the 
    vertical distance of the peak maximum to the line

    Parameters :
        V : (n x 1) numpy array;
            The measured potential
        smoothed_current : (n x 1) numpy array
            The smoothed approximation of the measured current
        max1 : int
            indice of the start of the peak
        min1 : int
            indice of the maximum of the peak
        max2 : int
            indice of the end of the peak
    Returns :
        peak_height : float;
            Vertical distance between the line joining (V[max1], smoothed_current[max1])
            and (V[max2], smoothed_current[max2]) to the peak maximum         
    """

    m,b = droite_param(V[max1],
                V[max2],
                smoothed_current[max1],
                smoothed_current[max2])

    peak_heigth = smoothed_current[ipeak] - droite(V[ipeak],m,b)

    return abs(peak_heigth)

def get_AUC(V,smoothed_current,max1,max2):
    """
    Isolates the current peaks and evaluate the area under the curve of the peak
    using the Simpsons algorythm for numerical integration 

    Parameters :
        V : (n x 1) numpy array;
            The measured potential
        smoothed_current : (n x 1) numpy array
            The smoothed approximation of the measured current
        max1 : int
            indice of the start of the peak
        max2 : int
            indice of the end of the peak
    Returns :
        auc : float;
            Area under the peak evaluated using the simpson's integration
            algorithm.
    """
    
    m,b = droite_param(V[max1],
            V[max2],
            smoothed_current[max1],
            smoothed_current[max2])

    only_peak = smoothed_current[max1:max2+1] - droite(V[max1:max2+1],m,b)
    return abs(simps(only_peak,V[max1:max2+1]))

def get_bg_avg(V,I,auc):
    """
    Evaluates the mean area under the curve of the signal without the peak.
    Parameters :
        V : (n x 1) numpy array;
            The measured potential
        I : (n x 1) numpy array
            The smoothed approximation of the measured current
        auc : float;
            Area under the peak
    Returns :
        background_avg : float;
            Mean background signal of a sample.  Evaluated by integrating the
            the whole signal to which we substarct the area under the peak. We
            then divide the result by the length of the potential interval.
    """
    return (abs(simps(I,V)) - auc)/(V.max() - V.min())

