def read_pscsv(data_path, encoding = "utf-16"):
    """
    Allows user to extract information contained in a csv file generated by 
    the PSTrace software. Returns two numpy.array object (V and I) and a pandas
    Serie (info).

    Parameters:
        data_path: str, pathlike object;
            Path pointing to the csv file that can be read by the
            pandas.read_csv function.
        encoding: str
            encoding used for the csv file. I have found that in
            PSTrace 5.8, the encoding used is utf-16
    Returns:
        V: numpy.array
            Voltage of the essay
        I: numpy.array
            Mesured current of the essay
        info: pd.Series
            information about the essay

    """
    data = pd.read_csv(data_path,encoding = encoding)

    info = pd.Series(data = [data.iloc[1,0],
                            data.iloc[2,1],
                            data.iloc[3,0] + ', ' + data.iloc[3,1],
                            data_path.name,
                            re.sub(r"_*-*[0-9]*(\([0-9]\))*\.csv","",data_path.name)],
                    index = ["method","time","units",'filename','label'])

    V = pd.Series(data = data.iloc[4:-1,0].values,
                name=data.iloc[3,0],
                dtype=float)
    I = pd.Series(data = data.iloc[4:-1,1].values,
                name=data.iloc[3,1],
                dtype=float)

    return np.float64(V.values), np.float64(I.values), info

def read_pssession(data_path, encoding = "utf-16"):
    """
    Allows user to extract information contained in a pssession file generated by 
    the PSTrace software. Returns two numpy.array object (V and I) and a pandas
    Serie (info).
    """
    with open(data_path,'r',encoding ='utf-16') as f:
        data = (f.readlines()[0]
                .rstrip('\ufeff')
                .replace('true','True')
                .replace('false','False'))
    
    d = dict(eval(data))

    V = np.array([i['v'] for i in d['measurements'][0]['dataset']['values'][1]['datavalues']])
    I = np.array([i['v'] for i in d['measurements'][0]['dataset']['values'][2]['datavalues']])

    time = d['measurements'][0]['method'].split('\r\n')[1].lstrip('#')
    method = d['measurements'][0]['title']

    E_unit = d['measurements'][0]['dataset']['values'][1]['unit']['s']
    I_unit = d['measurements'][0]['dataset']['values'][2]['unit']['s']

    info = pd.Series(data = [method,
                            time,E_unit +', ' +I_unit,
                            data_path.name,
                            re.sub(r"_*-*[0-9]*(\([0-9]\))*\.pssession","",data_path.name)],
                     index = ["method","time","units","filename","label"])

    return np.float64(V),np.float64(I),info


