def analysepeaks_vect(V,smooth,coeffs,max1,max2,min1):
    """
    From the currents values and the peaks positions, extracts all the information
    we could think of in a vectorised fashion.
    Parameters:
        V: m x n np.array;
            The potential values as a m x n array (m curves containing each n
            data points)
        smooth : m x n np.array;
            A smoothed version of the I data
        coeffs: (polyfit_order + 1) x n np.array:
            The coefficients of the polynome fit of the data.
        max1: list;
            a list containing the start of the peak for all curves
        max2: list;
            a list containing the end of the peak for all curves
        min1: list;
            a list containing the middle of the peak for all curves
    Returns:
        peak_height : list of floats;
            Vertical distance between the lines joining (V[max1], smoothed_current[max1])
            and (V[max2], smoothed_current[max2]) to the peak maximum for each 
            curves.        
        auc : list of floats;
            Area under the peak evaluated using the analytical integration of 
            fitted polynomes for each curves.
        peak_pos: list of floats;
            Position along the potential axis of the peak for each curves.
        avg_bg : list of floats;
            Mean background signal of all curves. Evaluated by integrating the
            the whole signal to which we substarct the area under the peak. We
            then divide the result by the length of the potential interval.
    """
    #current value at side
    y2 = smooth[np.arange(smooth.shape[0]),max2]
    y1 = smooth[np.arange(smooth.shape[0]),max1]

    #potential value at side
    x2 = V[np.arange(V.shape[0]),max2]
    x1 = V[np.arange(V.shape[0]),max1]

    #peak position and value
    peak_pos = V[np.arange(V.shape[0]),min1]
    ymin = smooth[np.arange(smooth.shape[0]),min1]

    #line parameters for all peak
    pente = (y2-y1)/(x2-x1)
    b = y2 - pente*x2
    droite_above = pente*peak_pos + b

    peak_pos[np.isnan(pente)] = np.nan
    ymin[np.isnan(pente)] = np.nan
    #evaluating peak height
    peak_height = abs(droite_above - ymin)
    peak_height[np.isnan(peak_height)] = 0

    #Area under curve
    primitive_coeffs = polyprimitivecoeffs_vect(coeffs)

    v_ = np.array([V[:,0],x1,x2,V[:,-1]])
    prim_value = np.polyval(primitive_coeffs,v_)

    auc = (pente/2 *(x1**2 - x2**2) + b*(x1 - x2))-(prim_value[1,:] - prim_value[2,:])
    auc[np.isnan(auc)] = 0

    avg_bg = (prim_value[-1,:] - prim_value[0,:] - auc)/(V[:,0]- V[:,-1])

    return peak_height,auc,peak_pos, avg_bg

