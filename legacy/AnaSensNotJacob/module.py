def read_multicurvespssession_UpperCase(data_path,scanrate = True, encoding = "utf-16"):
    """
    Similar to «read_pssession» except it can read a pssession file containing
    more than 1 curve.  This is usefull for example with the CV measures which
    are often contained in a single .pssession.

    Parameters:
        data_path: str or Path like object;
            Path pointing to the pssession file you want to read
        scanrate: Bool; default -> True
            True or False, if True, the function will extract the scanrate value
            from the pssession.  Should only be set to True in CV experiments
        encoding: str;
            encoding used in writing of the pssession files.  I found that  with
            the current version of the software, the encoding used is utf-16
    Returns:
        V: list;
            list of list containing all the potential values. e.g. The pssession
            contains 4 curves each containing 100 data points, V will be a list 
            containing 4 lists of 100 elements
        I: list;
            list of list containing all the current values. similar to V 
        info: pandas Series;
            Contains all the meta data of the experiment (time, name, etc)
    """
    with open(data_path,'r',encoding ='utf-16') as f:
        data = (f.readlines()[0]
                .rstrip('\ufeff')
                .replace('true','True')
                .replace('false','False'))
    
    d = dict(eval(data))['Measurements'][0]

    V = [[i['V'] for i in d['Curves'][j]['XAxisDataArray']['DataValues']] for j in range(len(d['Curves']))]
    I = [[i['V'] for i in d['Curves'][j]['YAxisDataArray']['DataValues']] for j in range(len(d['Curves']))]

    time = d['Method'].split('\r\n')[1].lstrip('#')
    method = d['Title']
    if scanrate:
        scan_rate = float(d['Method'].split('\r\n')[-6].lstrip('SCAN_RATE='))
    else:
        scan_rate = 0
    E_unit = d['DataSet']['Values'][1]['Unit']['S']
    I_unit = d['DataSet']['Values'][2]['Unit']['S']

    info = pd.Series(data = [method,
                            time,E_unit +', ' +I_unit,
                            data_path.name,
                            re.sub(r"_*-*[0-9]*(\([0-9]\))*\.pssession","",data_path.name),
                            scan_rate],
                     index = ["method","time","units","filename","label","scan_rate"])

    return np.float64(V),np.float64(I),info

